#!/usr/bin/env python3
"""Generate colocated documentation and check repository documentation offline."""
from pathlib import Path
from urllib.parse import unquote, urlsplit
import argparse
import hashlib
import json
import os
import re
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "docs/agent-mirrors.json"
MARKER = "<!-- generated by tools/docs/doc_tools.py; do not edit -->"
INLINE = re.compile(r'(!?\[[^\]\n]*\]\()(<[^>]+>|[^\s)]+)([^\n)]*\))')
REFERENCE = re.compile(r'^(\s{0,3}\[[^\]\n]+\]:\s*)(<[^>]+>|\S+)(.*)$', re.M)
HTML_LINK = re.compile(r'((?:href|src)=["\'])([^"\']+)(["\'])')


def text(path):
    return path.read_text(encoding="utf-8-sig")


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def inside(name):
    path = (ROOT / name).resolve()
    if not path.is_relative_to(ROOT):
        raise ValueError(f"Path outside repository: {name}")
    return path


def prose(body):
    """Ignore fenced examples; inline code is handled separately by callers."""
    result = []
    fence = None
    for line in body.splitlines(keepends=True):
        match = re.match(r'^\s*(`{3,}|~{3,})', line)
        if match:
            token = match[1]
            if fence is None:
                fence = token
            elif token[0] == fence[0] and len(token) >= len(fence):
                fence = None
            result.append("\n")
        else:
            result.append("\n" if fence else line)
    return "".join(result)


def slug(value):
    value = re.sub(r'<[^>]+>', '', value).replace('`', '').lower()
    value = re.sub(r'[^\w\-\s]', '', value, flags=re.UNICODE)
    return re.sub(r'\s', '-', value)


def anchors(body):
    found = set(re.findall(r'(?:id|name)=["\']([^"\']+)', prose(body)))
    counts = {}
    for heading in re.findall(r'^ {0,3}#{1,6}\s+(.+?)\s*#*\s*$', prose(body), re.M):
        base = slug(heading)
        n = counts.get(base, 0)
        counts[base] = n + 1
        found.add(base + (f"-{n}" if n else ""))
    return found


def local_target(raw, origin):
    value = raw.strip('<>')
    parsed = urlsplit(value)
    if parsed.scheme or parsed.netloc:
        return None
    path = unquote(parsed.path)
    target = (ROOT / path.lstrip('/')) if path.startswith('/') else (origin.parent / path if path else origin)
    return target.resolve(), unquote(parsed.fragment)


def relative(target, origin):
    return os.path.relpath(target, origin.parent).replace('\\', '/')


def entries():
    rows = json.loads(text(MANIFEST))["mirrors"]
    targets = set()
    for row in rows:
        source, target = inside(row["source"]), inside(row["target"])
        if not row["source"].startswith('docs/') or row["target"].startswith('docs/'):
            raise ValueError("Mirror sources must be in docs/ and targets outside docs/")
        if not source.is_file() or source == target or target in targets:
            raise ValueError(f"Invalid mirror: {row}")
        targets.add(target)
    return rows


def generated(row, rows):
    source, target = inside(row["source"]), inside(row["target"])
    parts = target.relative_to(ROOT).parts
    scope = ROOT.joinpath(*parts[:2]) if parts[0] == 'modules' else target.parent
    nearby = {inside(r['source']): inside(r['target']) for r in rows
              if inside(r['target']).is_relative_to(scope)}

    def rebase(match):
        resolved = local_target(match[2], source)
        if resolved is None:
            return match[0]
        dest, fragment = resolved
        dest = nearby.get(dest, dest)
        value = (relative(dest, target) if dest != target else '')
        if fragment:
            value += '#' + fragment
        if match[2].startswith('<'):
            value = '<' + value + '>'
        return match[1] + value + match[3]

    # Only rewrite link syntax outside fenced examples.
    original = text(source)
    visible = prose(original)
    replacements = []
    # Work linewise to preserve code examples and every source paragraph.
    lines = original.splitlines(keepends=True)
    flags = visible.splitlines(keepends=True)
    for line, flag in zip(lines, flags):
        if flag.strip():
            for pattern in (INLINE, REFERENCE, HTML_LINK):
                line = pattern.sub(rebase, line)
        replacements.append(line)
    header = (f'{MARKER}\n> 来源：[{row["source"]}]({relative(source, target)})\n'
              f'> source-sha256: `{digest(source)}`\n'
              '> 修改来源文件后，在仓库根运行 `python tools/docs/doc_tools.py sync`。\n\n')
    return header + ''.join(replacements)


def sync(rows):
    changed = 0
    for row in rows:
        target = inside(row['target'])
        expected = generated(row, rows)
        if target.exists() and not text(target).startswith(MARKER):
            raise ValueError(f"Refusing to overwrite handwritten file: {row['target']}")
        if not target.exists() or text(target) != expected:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected, encoding='utf-8', newline='\n')
            changed += 1
    print(f"Mirrors: {len(rows)}; updated: {changed}")


def pack():
    base = ROOT / 'skills/robot-doc-governance'
    dest = ROOT / 'dist/robot-doc-governance.zip'
    dest.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(dest, 'w', zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(base.rglob('*')):
            if path.is_file() and '__pycache__' not in path.parts:
                name = 'robot-doc-governance/' + path.relative_to(base).as_posix()
                info = zipfile.ZipInfo(name, date_time=(2026, 10, 17, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                archive.writestr(info, path.read_bytes())
    print('Skill package rebuilt: dist/robot-doc-governance.zip')


def check(rows):
    errors = []
    count = 0
    markdown = [p for p in ROOT.rglob('*.md') if not any(part in {'.git', '.audit-work', '__pycache__'} for part in p.relative_to(ROOT).parts)]
    cache = {p.resolve(): anchors(text(p)) for p in markdown}
    mirror_targets = {inside(row['target']) for row in rows}
    for path in markdown:
        if text(path).startswith(MARKER) and path.resolve() not in mirror_targets:
            errors.append('Unlisted generated file: ' + path.relative_to(ROOT).as_posix())
        body = re.sub(r'`[^`\n]+`', '', prose(text(path)))
        refs = {key.casefold().strip() for key in re.findall(r'^\s{0,3}\[([^\]]+)\]:', body, re.M)}
        for label, key in re.findall(r'\[([^\]]+)\]\[([^\]]*)\]', body):
            if (key or label).casefold().strip() not in refs:
                errors.append(f'{path.relative_to(ROOT)}: undefined reference {key or label}')
        for pattern in (INLINE, REFERENCE, HTML_LINK):
            for match in pattern.finditer(body):
                resolved = local_target(match[2], path)
                if resolved is None:
                    continue
                count += 1
                target, fragment = resolved
                label = f'{path.relative_to(ROOT)} -> {match[2]}'
                if not target.is_relative_to(ROOT):
                    errors.append(label + ' (outside repository)')
                elif not target.exists():
                    errors.append(label + ' (missing path)')
                elif fragment and target.suffix.lower() == '.md' and fragment not in cache.get(target, set()):
                    errors.append(label + ' (missing heading/id)')
    for row in rows:
        target = inside(row['target'])
        if not target.exists() or text(target) != generated(row, rows):
            errors.append('Stale mirror: ' + row['target'])
    inventory = json.loads(text(ROOT / 'docs/reports/2026-10-17-file-inventory.json'))
    preserved = 0
    for row in inventory['files']:
        path = inside(row['new_path'])
        if not path.is_file():
            errors.append('Missing migrated file: ' + row['new_path'])
        elif path.suffix in {'.pdf', '.jpg', '.docx', '.torrent'}:
            preserved += 1
            if digest(path) != row['sha256']:
                errors.append('Original bytes changed: ' + row['new_path'])
    base = ROOT / 'skills/robot-doc-governance'
    expected = {'robot-doc-governance/' + p.relative_to(base).as_posix(): p.read_bytes()
                for p in base.rglob('*') if p.is_file() and '__pycache__' not in p.parts}
    try:
        with zipfile.ZipFile(ROOT / 'dist/robot-doc-governance.zip') as z:
            if set(z.namelist()) != set(expected) or any(z.read(n) != b for n, b in expected.items()):
                errors.append('Skill ZIP differs from source; run pack')
    except (OSError, zipfile.BadZipFile) as exc:
        errors.append(f'Skill package: {exc}')
    print(f'Markdown: {len(markdown)}; local links: {count}; mirrors: {len(rows)}; preserved originals: {preserved}')
    for error in errors:
        print('ERROR: ' + error)
    print(f'Errors: {len(errors)}')
    return 1 if errors else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['sync', 'check', 'pack'])
    args = parser.parse_args()
    if args.command == 'pack':
        pack()
        return 0
    rows = entries()
    if args.command == 'sync':
        sync(rows)
        return 0
    return check(rows)


if __name__ == '__main__':
    sys.exit(main())
